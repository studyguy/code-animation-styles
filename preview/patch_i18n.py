def norm(t):
    """统一引号变体后再查表，避免 ASCII " 和全角 “” 对不上。"""
    for ch in ('"', '“', '”'):
        t = t.replace(ch, '‖')
    return t


FITN = {norm(k): v for k, v in FITS.items()}
CATN = {norm(k): v for k, v in CATS.items()}

missing_cat, missing_fit, missing_name = set(), set(), set()
for e in data['entries']:
    if not e.get('en'):
        if e['id'] in NAMES:
            e['en'] = NAMES[e['id']]
        elif e['name'] and re.match(r'^[\x00-\x7F]+$', e['name']):
            e['en'] = e['name']          # H 系列名字本来就是英文
        elif e['name']:
            missing_name.add(e['id'])
    if e['cat'] in CATS:
        e['catEn'] = CATS[e['cat']]
    elif norm(e['cat']) in CATN:
        e['catEn'] = CATN[norm(e['cat'])]
    else:
        missing_cat.add(e['cat'])
    if e.get('fit'):
        if e['fit'] in FITS:
            e['fitEn'] = FITS[e['fit']]
        elif norm(e['fit']) in FITN:
            e['fitEn'] = FITN[norm(e['fit'])]
        else:
            missing_fit.add(e['fit'])

